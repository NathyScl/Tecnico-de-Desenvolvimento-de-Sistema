dia = int(input("Digite um numero: "))

if(dia == 1):
    print("Domingo")
elif(dia == 2):
    print("Segunda-feira")
elif(dia == 3):
    print("terça-feira")
elif(dia == 4):
    print("Quarta_feira")
elif(dia == 5):
    print("Quinta-feira")
elif(dia == 6):
    print("Sexta-feira")
elif(dia == 7):
    print("Sabádo")
else:
    print("Dia inválido") 
